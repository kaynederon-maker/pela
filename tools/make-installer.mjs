// Packs the project source into a single self-extracting PowerShell script: install-pela.ps1
// Usage: node tools/make-installer.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(fileURLToPath(import.meta.url), "..", "..");
const OUT = join(ROOT, "install-pela.ps1");
const SKIP_DIRS = new Set(["node_modules", "artifacts", "cache", "coverage", "typechain-types", ".next", ".git"]);
const SKIP_FILE = /^(\.env(\.local)?|.*\.db(-journal|-wal|-shm)?|install-pela\.ps1|coverage\.json|next-env\.d\.ts)$/;
const DEFAULT_TARGET = "C:\\Users\\USER\\OneDrive\\Documents\\AI Individual Projects\\Blockchain\\Pela";

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      if (!SKIP_DIRS.has(name)) yield* walk(full);
    } else if (!SKIP_FILE.test(name)) {
      yield full;
    }
  }
}

const files = [...walk(ROOT)].map((full) => ({
  path: relative(ROOT, full).split(sep).join("/"),
  b64: readFileSync(full).toString("base64"),
}));

const entries = files.map((f) => `  @{ p = '${f.path.replace(/'/g, "''")}'; b = '${f.b64}' }`).join(",\n");

const script = `# Pela installer, generated by tools/make-installer.mjs on ${new Date().toISOString()}
# Recreates the full Pela project (${files.length} files), then run: .\\setup.ps1 -Start
#   powershell -ExecutionPolicy Bypass -File .\\install-pela.ps1 [-Target <folder>] [-Force]
param(
    [string]$Target = '${DEFAULT_TARGET}',
    [switch]$Force
)
$ErrorActionPreference = 'Stop'

if ((Test-Path -LiteralPath $Target) -and (Get-ChildItem -LiteralPath $Target -Force | Select-Object -First 1) -and -not $Force) {
    throw "$Target is not empty. Re-run with -Force to overwrite Pela's files there."
}

$files = @(
${entries}
)

foreach ($f in $files) {
    $dest = Join-Path $Target $f.p
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $dest) | Out-Null
    [IO.File]::WriteAllBytes($dest, [Convert]::FromBase64String($f.b))
}

Write-Host "Wrote $($files.Count) files to $Target" -ForegroundColor Green
Write-Host "Next:  cd \`"$Target\`"; .\\setup.ps1 -Start" -ForegroundColor Green
`;

writeFileSync(OUT, script);
console.log(`install-pela.ps1: ${files.length} files, ${(script.length / 1024 / 1024).toFixed(2)} MB`);
